/**
 * Tool comparison: the second experiment, and the test of the abstraction.
 * It inverts method grounding's axis — the design direction is held fixed (one
 * complete specification) and the TOOL varies across arms (Stitch vs. a raw
 * model vs. another). It asks: handed the same direction, how faithfully does
 * each tool reproduce it? Scored by fidelity to the handed tokens, not escape.
 *
 * This is what proves the experiment, tool, and metric seams are shaped right:
 * the same PlannedCell shape carries a per-cell `tool` that genuinely varies,
 * the metric binding points at a different check, and nothing in generate.ts or
 * measure.ts needs to know which axis it is.
 *
 * Running it end to end needs two pieces that don't exist yet — a model adapter
 * (so `getTool("gemini")` resolves) and the fidelity metric — so this is a
 * runnable-once-those-land declaration. The shape is validated now; the wiring
 * follows. Pass the tools to compare as the arms, e.g. --arms stitch,gemini.
 */
import { cellName, type DesignCase } from "../cases.ts";
import type { Experiment, PlannedCell, PlanOptions } from "./types.ts";

/** The arm key whose DESIGN.md is the fixed direction every tool must
 *  reproduce — the complete specification by preference. */
function fixedDirectionArm(c: DesignCase): string | null {
  for (const preferred of ["full-spec", "object"]) {
    if (c.armFiles.has(preferred)) return preferred;
  }
  return [...c.armFiles.keys()][0] ?? null;
}

export const toolComparison: Experiment = {
  name: "tool-comparison",
  description:
    "One brief, one fixed design direction, generated by several tools. Tests how faithfully each tool reproduces the same handed direction.",
  metric: "fidelity-to-direction",

  plan(cases: DesignCase[], options: PlanOptions): PlannedCell[] {
    // Here the arms ARE the tools to compare; absent a list, fall back to the
    // single configured tool (a comparison of one — honest, just not yet plural).
    const tools = options.arms ?? [options.defaultTool];
    const cells: PlannedCell[] = [];
    for (const c of cases) {
      const directionArm = fixedDirectionArm(c);
      const armFile = directionArm ? (c.armFiles.get(directionArm) ?? null) : null;
      for (const tool of tools) {
        for (const channel of options.channels) {
          // The tool is the axis; the direction is the same fixed arm for every tool.
          cells.push({ caseKey: c.key, cell: cellName(tool, channel), tool, armKey: tool, directionArm, armFile, channel });
        }
      }
    }
    return cells;
  },
};
